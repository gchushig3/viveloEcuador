import 'reflect-metadata';
import { readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import {
  afterAll,
  afterEach,
  beforeAll,
  beforeEach,
  describe,
  expect,
  it,
} from '@jest/globals';
import type { EntityManager, QueryRunner } from 'typeorm';
import { validateEnvironment } from '../../src/config/environment.js';
import { databaseOptions } from '../../src/database/database-options.js';
import { createIdentityDataSource } from '../../src/database/identity-domains.js';
import { applyIdentitySchema } from '../../src/database/apply-identity-schema.js';
import {
  RolEntity,
  UsuarioEntity,
  UsuarioRolEntity,
  SesionEntity,
  TokenVerificacionEntity,
  UsuarioRolesView,
} from '../../src/database/entities/index.js';

const env = validateEnvironment(process.env);
if (
  env.NODE_ENV !== 'test' ||
  env.APP_ENV !== 'test' ||
  env.DB_DATABASE !== 'ms_identity_test' ||
  !['localhost', '127.0.0.1'].includes(env.DB_HOST) ||
  env.DB_PORT !== 5442
)
  throw new Error(
    'Integration requires isolated ms_identity_test on loopback:5442',
  );
const source = createIdentityDataSource(databaseOptions(env));
let runner: QueryRunner;
let manager: EntityManager;
let user: UsuarioEntity;
let assigner: UsuarioEntity;
let client: RolEntity;
let sql: string;
let passwordHash: string;
const hash = (value: string) =>
  createHash('sha256').update(value).digest('hex');

async function sqlState(
  action: () => Promise<unknown>,
  state: string,
): Promise<void> {
  await runner.query('SAVEPOINT expected_failure');
  try {
    await expect(action()).rejects.toMatchObject({
      driverError: { code: state },
    });
  } finally {
    await runner.query('ROLLBACK TO SAVEPOINT expected_failure');
    await runner.query('RELEASE SAVEPOINT expected_failure');
  }
}
async function session(): Promise<SesionEntity> {
  return manager.save(SesionEntity, {
    usu_id: user.usu_id,
    ses_token_hash: hash('session fixture'),
    ses_expira_en: new Date(Date.now() + 60000),
  });
}
async function token(): Promise<TokenVerificacionEntity> {
  return manager.save(TokenVerificacionEntity, {
    usu_id: user.usu_id,
    tokv_token: hash('verification fixture'),
    tokv_tipo: 'EMAIL',
    tokv_expira_en: new Date(Date.now() + 60000),
  });
}
async function association(): Promise<void> {
  await manager.insert(UsuarioRolEntity, {
    usu_id: user.usu_id,
    rol_id: client.rol_id,
    usr_asignado_por: assigner.usu_id,
  });
}

describe('Identity persistence on real PostgreSQL 16', () => {
  beforeAll(async () => {
    sql = await readFile(
      new URL('../../database/migrations/001-identity.sql', import.meta.url),
      'utf8',
    );
    await source.initialize();
    const [target] = await source.query<
      Array<{ database: string; version: number }>
    >(
      "SELECT current_database() AS database,current_setting('server_version_num')::int AS version",
    );
    expect(target?.database).toBe('ms_identity_test');
    expect(target?.version).toBeGreaterThanOrEqual(160000);
    expect(target?.version).toBeLessThan(170000);
    const tables = await source.query<unknown[]>(
      "SELECT tablename FROM pg_tables WHERE schemaname='public'",
    );
    if (!tables.length) await applyIdentitySchema(source, sql);
    // bcrypt fixture generated by approved pgcrypto, not an authentication implementation.
    const [row] = await source.query<Array<{ hash: string }>>(
      "SELECT crypt('test-fixture-only',gen_salt('bf',4)) AS hash",
    );
    if (!row) throw new Error('Missing fixture hash');
    passwordHash = row.hash;
  });
  beforeEach(async () => {
    runner = source.createQueryRunner();
    await runner.connect();
    await runner.startTransaction();
    manager = runner.manager;
    user = await manager.save(UsuarioEntity, {
      usu_correo: 'fixture@identity.local',
      usu_password: passwordHash,
      usu_nombre: 'Fixture',
      usu_apellido: 'Identity',
    });
    assigner = await manager.save(UsuarioEntity, {
      usu_correo: 'assigner@identity.local',
      usu_password: passwordHash,
      usu_nombre: 'Asignador',
      usu_apellido: 'Fixture',
    });
    client = await manager.findOneByOrFail(RolEntity, {
      rol_nombre: 'CLIENTE',
    });
  });
  afterEach(async () => {
    if (runner?.isTransactionActive) await runner.rollbackTransaction();
    if (runner && !runner.isReleased) await runner.release();
  });
  afterAll(async () => {
    if (!source.isInitialized) return;
    try {
      for (const entity of [
        UsuarioEntity,
        UsuarioRolEntity,
        SesionEntity,
        TokenVerificacionEntity,
      ])
        expect(await source.getRepository(entity).count()).toBe(0);
      expect(await source.getRepository(RolEntity).count()).toBe(3);
    } finally {
      await source.destroy();
    }
  });

  it('preserves the approved SQL checksum and exactly five tables', async () => {
    const provenance = JSON.parse(
      await readFile('database/source.json', 'utf8'),
    ) as { sha256: string };
    expect(hash(sql)).toBe(provenance.sha256);
    const tables = await manager.query<Array<{ tablename: string }>>(
      "SELECT tablename FROM pg_tables WHERE schemaname='public' ORDER BY tablename",
    );
    expect(tables.map((row) => row.tablename)).toEqual([
      'rol',
      'sesion',
      'token_verificacion',
      'usuario',
      'usuario_rol',
    ]);
    expect(source.options).toMatchObject({
      synchronize: false,
      dropSchema: false,
      migrationsRun: false,
    });
  });

  it.each(['rol', 'usuario', 'usuario_rol', 'sesion', 'token_verificacion'])(
    'preserves columns, types, defaults and identity metadata: %s',
    async (table) => {
      interface Column {
        name: string;
        type: string;
        nullable: boolean;
        identity: boolean;
        default: string | null;
      }
      const manifest = JSON.parse(
        await readFile('database/schema-manifest.json', 'utf8'),
      ) as { tables: Record<string, { columns: Column[] }> };
      const expected = manifest.tables[table]?.columns;
      if (!expected) throw new Error('Missing manifest table');
      const rows = await manager.query<
        Array<{
          column_name: string;
          data_type: string;
          domain_name: string | null;
          is_nullable: string;
          identity_generation: string | null;
          column_default: string | null;
          character_maximum_length: number | null;
        }>
      >(
        "SELECT column_name,data_type,domain_name,is_nullable,identity_generation,column_default,character_maximum_length FROM information_schema.columns WHERE table_schema='public' AND table_name=$1 ORDER BY ordinal_position",
        [table],
      );
      expect(rows.map((row) => row.column_name)).toEqual(
        expected.map((column) => column.name),
      );
      const metadata = source.getMetadata(table);
      expect(
        metadata.columns.map((column) => column.databaseName).sort(),
      ).toEqual(expected.map((column) => column.name).sort());
      for (const column of expected) {
        const actual = rows.find((row) => row.column_name === column.name);
        expect(actual?.is_nullable).toBe(column.nullable ? 'YES' : 'NO');
        expect(
          metadata.findColumnWithDatabaseName(column.name)?.isNullable,
        ).toBe(column.nullable);
        if (column.identity) expect(actual?.identity_generation).toBe('ALWAYS');
        expect(actual?.domain_name).toBe(
          column.type.startsWith('dom_') ? column.type : null,
        );
        if (column.type.startsWith('dom_'))
          expect(metadata.findColumnWithDatabaseName(column.name)?.type).toBe(
            column.type,
          );
        else if (column.type.startsWith('VARCHAR')) {
          expect(actual?.data_type).toBe('character varying');
          expect(actual?.character_maximum_length).toBe(
            Number(column.type.match(/\d+/)?.[0]),
          );
        } else
          expect(actual?.data_type).toBe(
            (
              {
                SMALLINT: 'smallint',
                BIGINT: 'bigint',
                BOOLEAN: 'boolean',
                UUID: 'uuid',
                TIMESTAMPTZ: 'timestamp with time zone',
                DATE: 'date',
              } as Record<string, string>
            )[column.type],
          );
        if (column.default)
          expect(actual?.column_default).toContain(
            column.default === 'TRUE'
              ? 'true'
              : column.default === 'FALSE'
                ? 'false'
                : column.default,
          );
      }
    },
  );

  it('preserves three domains, explicit indexes and named constraints', async () => {
    const domains = await manager.query<Array<{ domain_name: string }>>(
      "SELECT domain_name FROM information_schema.domains WHERE domain_schema='public' ORDER BY domain_name",
    );
    expect(domains.map((row) => row.domain_name)).toEqual([
      'dom_correo',
      'dom_documento',
      'dom_telefono',
    ]);
    const indexes = await manager.query<Array<{ indexname: string }>>(
      "SELECT indexname FROM pg_indexes WHERE schemaname='public' AND indexname LIKE 'ix_%'",
    );
    expect(indexes.map((row) => row.indexname).sort()).toEqual(
      [...sql.matchAll(/CREATE INDEX (\w+)/g)]
        .map((match) => match[1])
        .sort((left, right) => (left ?? '').localeCompare(right ?? '')),
    );
    const constraints = await manager.query<Array<{ conname: string }>>(
      "SELECT conname FROM pg_constraint WHERE connamespace='public'::regnamespace",
    );
    for (const match of sql.matchAll(/CONSTRAINT (\w+)/g))
      expect(constraints.map((row) => row.conname)).toContain(match[1]);
    for (const meta of source.entityMetadatas) {
      for (const check of meta.checks)
        expect(constraints.map((row) => row.conname)).toContain(check.name);
      for (const unique of meta.uniques)
        expect(constraints.map((row) => row.conname)).toContain(unique.name);
    }
  });

  it('loads the original three roles by name without creating an administrator account', async () => {
    const roles = await manager.find(RolEntity, { order: { rol_id: 'ASC' } });
    expect(
      roles.map((role) => [
        role.rol_nombre,
        role.rol_descripcion,
        role.rol_activo,
      ]),
    ).toEqual([
      ['ADMIN', 'Administrador total del marketplace', true],
      ['OPERADOR', 'Empresa que opera atracciones', true],
      ['CLIENTE', 'Usuario que compra y reserva', true],
    ]);
    // Only the two transaction-local fixtures exist; neither has an assigned role.
    expect(await manager.count(UsuarioEntity)).toBe(2);
    expect(await manager.count(UsuarioRolEntity)).toBe(0);
  });

  it('rejects reapplication and tampered SQL without duplicating roles', async () => {
    await expect(applyIdentitySchema(source, sql)).rejects.toThrow(
      'ya contiene objetos',
    );
    await expect(
      applyIdentitySchema(source, sql + '\nSELECT 1;'),
    ).rejects.toThrow('approved Identity block');
    expect(await manager.count(RolEntity)).toBe(3);
  });

  it('preserves defaults, timestamp types and date-only strings', async () => {
    expect(user).toMatchObject({
      usu_verificado: false,
      usu_activo: true,
      usu_documento: null,
      usu_ultimo_acceso: null,
    });
    expect(typeof user.usu_id).toBe('string');
    expect(user.usu_creado_en).toBeInstanceOf(Date);
    await manager.update(UsuarioEntity, user.usu_id, {
      usu_fecha_nacimiento: '2000-01-02',
    });
    expect(
      (await manager.findOneByOrFail(UsuarioEntity, { usu_id: user.usu_id }))
        .usu_fecha_nacimiento,
    ).toBe('2000-01-02');
  });

  it('hides password and token hashes unless explicitly selected', async () => {
    const savedSession = await session();
    const savedToken = await token();
    expect(savedSession.ses_id).toMatch(/^[a-f0-9-]{36}$/);
    expect(savedSession.ses_revocada).toBe(false);
    expect(savedToken.tokv_usado).toBe(false);
    expect(
      (await manager.findOneByOrFail(UsuarioEntity, { usu_id: user.usu_id }))
        .usu_password,
    ).toBeUndefined();
    expect(
      (
        await manager.findOneByOrFail(SesionEntity, {
          ses_id: savedSession.ses_id,
        })
      ).ses_token_hash,
    ).toBeUndefined();
    expect(
      (
        await manager.findOneByOrFail(TokenVerificacionEntity, {
          tokv_id: savedToken.tokv_id,
        })
      ).tokv_token,
    ).toBeUndefined();
    const selected = await manager
      .getRepository(SesionEntity)
      .createQueryBuilder('s')
      .addSelect('s.ses_token_hash')
      .where('s.ses_id=:id', { id: savedSession.ses_id })
      .getOneOrFail();
    expect(selected.ses_token_hash).toBe(hash('session fixture'));
    const selectedToken = await manager
      .getRepository(TokenVerificacionEntity)
      .createQueryBuilder('t')
      .addSelect('t.tokv_token')
      .where('t.tokv_id=:id', { id: savedToken.tokv_id })
      .getOneOrFail();
    expect(selectedToken.tokv_token).toHaveLength(64);
  });

  it('loads all internal relationships and nullable assigner', async () => {
    await association();
    const savedSession = await session();
    const savedToken = await token();
    const link = await manager.findOneOrFail(UsuarioRolEntity, {
      where: { usu_id: user.usu_id, rol_id: client.rol_id },
      relations: { usuario: true, rol: true, asignador: true },
    });
    expect(link.usuario.usu_id).toBe(user.usu_id);
    expect(link.rol.rol_nombre).toBe('CLIENTE');
    expect(link.asignador?.usu_id).toBe(assigner.usu_id);
    expect(
      (
        await manager.findOneOrFail(SesionEntity, {
          where: { ses_id: savedSession.ses_id },
          relations: { usuario: true },
        })
      ).usuario.usu_id,
    ).toBe(user.usu_id);
    expect(
      (
        await manager.findOneOrFail(TokenVerificacionEntity, {
          where: { tokv_id: savedToken.tokv_id },
          relations: { usuario: true },
        })
      ).usuario.usu_id,
    ).toBe(user.usu_id);
  });

  it('view filters inactive users and inactive roles', async () => {
    await association();
    expect(await manager.count(UsuarioRolesView)).toBe(1);
    await manager.update(RolEntity, client.rol_id, { rol_activo: false });
    expect(await manager.count(UsuarioRolesView)).toBe(0);
    await manager.update(RolEntity, client.rol_id, { rol_activo: true });
    await manager.update(UsuarioEntity, user.usu_id, { usu_activo: false });
    expect(await manager.count(UsuarioRolesView)).toBe(0);
  });

  it.each([
    ['usu_correo', 'invalid'],
    ['usu_documento', '123'],
    ['usu_telefono', 'abc'],
    ['usu_nombre', ' '],
    ['usu_apellido', ''],
  ])('rejects invalid %s', async (column, value) => {
    await sqlState(
      () =>
        manager.query(`UPDATE usuario SET ${column}=$1 WHERE usu_id=$2`, [
          value,
          user.usu_id,
        ]),
      '23514',
    );
  });
  it('rejects unsupported verification purpose', async () => {
    await sqlState(
      () =>
        manager.save(TokenVerificacionEntity, {
          usu_id: user.usu_id,
          tokv_token: hash('invalid purpose'),
          tokv_tipo: 'ADMIN',
          tokv_expira_en: new Date(),
        }),
      '23514',
    );
  });
  it.each(['usu_correo', 'usu_documento'])(
    'enforces user uniqueness: %s',
    async (column) => {
      if (column === 'usu_documento')
        await manager.update(UsuarioEntity, user.usu_id, {
          usu_documento: '1234567890',
        });
      await sqlState(
        () =>
          manager.query(`UPDATE usuario SET ${column}=$1 WHERE usu_id=$2`, [
            column === 'usu_correo' ? user.usu_correo : '1234567890',
            assigner.usu_id,
          ]),
        '23505',
      );
    },
  );
  it('enforces unique role names and composite assignments', async () => {
    await association();
    await sqlState(
      () =>
        manager.save(RolEntity, {
          rol_nombre: 'CLIENTE',
          rol_descripcion: 'Duplicate fixture',
        }),
      '23505',
    );
    await sqlState(
      () =>
        manager.insert(UsuarioRolEntity, {
          usu_id: user.usu_id,
          rol_id: client.rol_id,
        }),
      '23505',
    );
  });
  it('enforces unique session and verification hashes', async () => {
    await session();
    await token();
    await sqlState(session, '23505');
    await sqlState(token, '23505');
  });
  it('requires internal users and supports RESTRICT and SET NULL', async () => {
    await association();
    await sqlState(
      () =>
        manager.save(SesionEntity, {
          usu_id: '9223372036854775807',
          ses_token_hash: hash('no user'),
          ses_expira_en: new Date(),
        }),
      '23503',
    );
    await sqlState(() => manager.delete(RolEntity, client.rol_id), '23503');
    await manager.delete(UsuarioEntity, assigner.usu_id);
    expect(
      (
        await manager.findOneByOrFail(UsuarioRolEntity, {
          usu_id: user.usu_id,
          rol_id: client.rol_id,
        })
      ).usr_asignado_por,
    ).toBeNull();
  });
  it('cascades physical user deletion only within Identity', async () => {
    await association();
    await session();
    await token();
    await manager.delete(UsuarioEntity, user.usu_id);
    for (const entity of [
      UsuarioRolEntity,
      SesionEntity,
      TokenVerificacionEntity,
    ])
      expect(await manager.count(entity)).toBe(0);
    expect(await manager.count(RolEntity)).toBe(3);
    const foreign = await manager.query<Array<{ target: string }>>(
      "SELECT confrelid::regclass::text AS target FROM pg_constraint WHERE contype='f' AND connamespace='public'::regnamespace",
    );
    expect(foreign).toHaveLength(5);
    expect(
      foreign.every((key) => ['usuario', 'rol'].includes(key.target)),
    ).toBe(true);
  });
  it('preserves BIGINT beyond Number.MAX_SAFE_INTEGER', async () => {
    const id = '9007199254740993';
    await manager.query(
      'INSERT INTO usuario (usu_id,usu_correo,usu_password,usu_nombre,usu_apellido) OVERRIDING SYSTEM VALUE VALUES ($1,$2,$3,$4,$5)',
      [id, 'bigint@identity.local', passwordHash, 'Bigint', 'Fixture'],
    );
    await manager.insert(UsuarioRolEntity, {
      usu_id: id,
      rol_id: client.rol_id,
    });
    expect(
      (
        await manager.findOneByOrFail(UsuarioRolEntity, {
          usu_id: id,
          rol_id: client.rol_id,
        })
      ).usu_id,
    ).toBe(id);
  });
  it('preserves the SQL trigger controlling user update timestamps', async () => {
    await manager.query(
      "UPDATE usuario SET usu_actualizado_en='2000-01-01T00:00:00Z' WHERE usu_id=$1",
      [user.usu_id],
    );
    const loaded = await manager.findOneByOrFail(UsuarioEntity, {
      usu_id: user.usu_id,
    });
    expect(loaded.usu_actualizado_en.getTime()).toBeGreaterThan(
      Date.parse('2000-01-01T00:00:00Z'),
    );
  });
});
